package io.rqlite;

import io.rqlite.client.L4Error;
import io.rqlite.client.L4Err;
import io.rqlite.client.L4Result;
import io.rqlite.client.L4StatementException;
import io.rqlite.json.Json;
import j8spec.annotation.DefinedOrder;
import j8spec.junit.J8SpecRunner;
import org.junit.runner.RunWith;

import java.io.IOException;
import java.sql.BatchUpdateException;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;

import static io.rqlite.jdbc.L4Err.*;
import static j8spec.J8Spec.*;
import static org.junit.Assert.*;

@DefinedOrder
@RunWith(J8SpecRunner.class)
public class L4ErrTest {

  static {
    it("Builds client-layer exceptions", () -> {
      assertTrue(L4Err.tooManyRedirects(3) instanceof IllegalStateException);
      assertTrue(L4Err.requestError("boom").getMessage().contains("boom"));
      assertTrue(L4Err.missingResult() instanceof IllegalStateException);
      assertTrue(L4Err.httpTransportError("POST", 500, "http://x", new RuntimeException()) instanceof IllegalStateException);
      assertTrue(L4Err.invalidTimeout(-1) instanceof IllegalArgumentException);
      assertTrue(L4Err.mixedStatementParams() instanceof IllegalStateException);
      assertTrue(L4Err.negativeParamIndex(-2) instanceof IllegalArgumentException);
      assertTrue(L4Err.emptyStatement() instanceof IllegalStateException);
      assertTrue(L4Err.unknownColumn("c") instanceof IllegalArgumentException);
      assertTrue(L4Err.invalidErrorsFormat("v3") instanceof IllegalArgumentException);
      assertTrue(L4Err.optionsUpdateFailed(new RuntimeException()) instanceof IllegalStateException);
      assertTrue(L4Err.noClientCertificates("/x") instanceof IllegalArgumentException);
      assertTrue(L4Err.invalidClientKey("/x") instanceof IllegalArgumentException);
      assertTrue(L4Err.unsupportedKeyAlgorithm("/x") instanceof IllegalArgumentException);
      assertTrue(L4Err.responseError(500, "bad").getMessage().contains("500"));
    });

    it("Builds connection and driver failures", () -> {
      assertTrue(blockExecutionFailed(new RuntimeException("x")) instanceof SQLException);
      assertEquals(SqlStateGeneralError, blockExecutionFailed(new RuntimeException("x")).getSQLState());

      var cce = clientCreationFailed(new RuntimeException("x"));
      assertEquals(SqlStateConnectionError, cce.getSQLState());

      assertTrue(driverRegistrationFailed(new RuntimeException()) instanceof RuntimeException);
      assertTrue(clientInfoError(new SQLException("x", "HY000")) instanceof SQLClientInfoException);
      assertTrue(streamWriteFailed(new RuntimeException()) instanceof IOException);
      assertTrue(lobWriteFailed(new RuntimeException()) instanceof IllegalStateException);
    });

    it("Builds batch exceptions", () -> {
      var constraint = new L4Error();
      constraint.message = "unique constraint failed";
      constraint.code = 19;
      constraint.extendedCode = 2067;

      var bue = batchEntryFailed(constraint, new int[]{1, 0});
      assertEquals(SqlStateIntegrityConstraint, bue.getSQLState());
      assertEquals(2067, bue.getErrorCode());
      assertArrayEquals(new int[]{1, 0}, bue.getUpdateCounts());

      var failed = batchFailed(new RuntimeException("x"), new int[]{-3});
      assertEquals(SqlStateConnectionError, failed.getSQLState());
      assertArrayEquals(new int[]{-3}, failed.getUpdateCounts());
      assertTrue(failed instanceof BatchUpdateException);
    });

    it("Builds argument errors", () -> {
      assertEquals(SqlStateInvalidParam, batchTooLarge(3, 2).getSQLState());
      assertEquals(SqlStateInvalidParam, invalidAutoGeneratedKeys().getSQLState());
      assertEquals(SqlStateInvalidParam, invalidHoldability(7).getSQLState());
      assertEquals(SqlStateInvalidParam, nullExecutor().getSQLState());
      assertEquals(SqlStateInvalidQuery, preparedStatementNoArgs("executeQuery").getSQLState());
      assertEquals(SqlStateInvalidQuery, noConnection().getSQLState());
      assertEquals(SqlStateGeneralError, noResultSet().getSQLState());
      assertEquals(SqlStateGeneralError, statementIsQuery().getSQLState());
      assertEquals(SqlStateInvalidParam, invalidBlob().getSQLState());
    });

    it("Builds resource errors preserving exception types", () -> {
      assertTrue(resourceNotFound("/x") instanceof IOException);
      assertTrue(resourceLoadFailed(new RuntimeException()) instanceof IllegalArgumentException);
      assertTrue(nullJdbcType() instanceof IllegalArgumentException);
      assertTrue(nullSql() instanceof IllegalArgumentException);
    });

    it("Has consistent SQLStates for former null-state factories", () -> {
      assertEquals(SqlStateInvalidType, badType(1, "v").getSQLState());
      assertEquals(SqlStateGeneralError, badInterface().getSQLState());
      assertEquals(SqlStateFeatureNotSupported, badUnwrap(String.class).getSQLState());
      assertEquals(SqlStateInvalidTransaction, badState("boom", new RuntimeException()).getSQLState());
    });

    it("Folds base64 decoding into the format error", () -> {
      var e = badB64(1, "not-base64", new RuntimeException());
      assertTrue(e.getMessage().contains("base64"));
      assertEquals(SqlStateInvalidType, e.getSQLState());
    });

    it("Rethrows existing SQLExceptions instead of re-wrapping", () -> {
      var original = new SQLException("boom", SqlStateFeatureNotSupported);
      assertSame(original, badParam(original));
      assertSame(original, badConversion(1, "v", original));
      assertSame(original, blockExecutionFailed(original));

      var constraint = new L4Error();
      constraint.message = "unique constraint failed";
      constraint.code = 19;
      constraint.extendedCode = 2067;
      var mapped = blockExecutionFailed(new L4StatementException(constraint));
      assertEquals(SqlStateIntegrityConstraint, mapped.getSQLState());
      assertEquals(2067, mapped.getErrorCode());

      // Non-SQL causes are still wrapped.
      assertEquals(SqlStateInvalidParam, badParam(new RuntimeException("x")).getSQLState());
      assertEquals(SqlStateInvalidConversion, badConversion(1, "v", new RuntimeException("x")).getSQLState());
      assertEquals(SqlStateGeneralError, blockExecutionFailed(new RuntimeException("x")).getSQLState());
    });

    it("Routes column and row checks through factories", () -> {
      var result = new L4Result(Json.object());
      result.columns.add("id");
      result.values.add(java.util.Arrays.asList("1"));

      try {
        checkColumn(2, result);
        fail("Expected SQLException");
      } catch (SQLException e) {
        assertEquals(SqlStateInvalidColumn, e.getSQLState());
        assertTrue(e.getMessage().contains("Invalid column index"));
      }

      try {
        checkRow(0, result, true);
        fail("Expected SQLException");
      } catch (SQLException e) {
        assertEquals(SqlStateGeneralError, e.getSQLState());
      }

      try {
        checkRow(5, result, false);
        fail("Expected SQLException");
      } catch (SQLException e) {
        assertEquals(SqlStateInvalidCursor, e.getSQLState());
      }
    });
  }

}
